#ifndef SENSOR_DEFAULTS_H
#define SENSOR_DEFAULTS_H

#define SENSOR_EXPOSURE_SETTING (0x11CC)
#define SENSOR_AGAIN_SETTING    (0xB4)
#define SENSOR_DGAIN_SETTING    (0xDDF)
#define SENSOR_FRAMELEN_SETTING (0x1908)

#define SENSOR_AGAIN_MAX        (232)
#define SENSOR_DGAIN_MIN        (0x0100)
#define SENSOR_DGAIN_MAX        (0x0FFF)
#define SENSOR_EXPOSURE_MIN     (1)
#define SENSOR_EXPOSURE_MARGIN  (4)
#define SENSOR_FRAMELEN_MIN     (2464 + 32)
#define SENSOR_FRAMELEN_MAX     (0xFFFE)

#ifdef __cplusplus
#define SENSOR_DEFAULTS_ASSERT static_assert
#else
#define SENSOR_DEFAULTS_ASSERT _Static_assert
#endif

SENSOR_DEFAULTS_ASSERT(SENSOR_EXPOSURE_SETTING >= SENSOR_EXPOSURE_MIN, "exposure below 1 line");
SENSOR_DEFAULTS_ASSERT(SENSOR_EXPOSURE_SETTING <= SENSOR_FRAMELEN_SETTING - SENSOR_EXPOSURE_MARGIN,
                       "exposure must be <= framelen - 4");
SENSOR_DEFAULTS_ASSERT(SENSOR_FRAMELEN_SETTING >= SENSOR_FRAMELEN_MIN && SENSOR_FRAMELEN_SETTING <= SENSOR_FRAMELEN_MAX,
                       "framelen out of range");
SENSOR_DEFAULTS_ASSERT(SENSOR_AGAIN_SETTING <= SENSOR_AGAIN_MAX, "analogue gain out of range");
SENSOR_DEFAULTS_ASSERT(SENSOR_DGAIN_SETTING >= SENSOR_DGAIN_MIN && SENSOR_DGAIN_SETTING <= SENSOR_DGAIN_MAX,
                       "digital gain out of range");

#endif
